<?php 

// ... Introdução do for:
for ($expression= 0;   $expression <= 1; $expression++) { 
    print "expression is: \n $expression";
    
}


// ... Faça a tabuada do número 7 usando o for:
$number = 7;

for ($i=1; $i <=10 ; $i++) { 
    echo "$number x $i = " . ($number * $i) . "\n";
}

// ... Fazer uma contagem regressiva de 10 até o número 1:
$degree = 10;
for (; $degree>=1; $degree--) { 
    echo"$degree \n" ;
}
 

?>